        <h2 class="doc-h2 text-lg sm:text-xl font-bold text-amber-900 border-l-4 border-amber-600 pl-3">2. ປະຫວັດສາດ ແລະ ສາຍທານການສືບທອດແຫ່ງວິຊາສວຽນຄົງ</h2>
